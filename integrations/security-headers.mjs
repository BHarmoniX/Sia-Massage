// Writes host security config into the build output, generated from config/security.mjs:
//   _headers   → Cloudflare Pages / Netlify
//   .htaccess  → Hostinger and other Apache hosts
// Both are always written so one build can be uploaded to any host.

import { writeFile } from 'node:fs/promises';
import {
  blockedPathPatterns,
  immutableAssetHeaders,
  securityHeaders,
} from '../config/security.mjs';

function cloudflareHeaders() {
  const block = (path, headers) =>
    [path, ...Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`)].join('\n');
  return [
    block('/*', securityHeaders),
    block('/_astro/*', immutableAssetHeaders),
    '',
  ].join('\n\n');
}

function apacheHtaccess() {
  const esc = (v) => v.replace(/"/g, '\\"');
  const headerLines = Object.entries(securityHeaders)
    .map(([k, v]) => `  Header always set ${k} "${esc(v)}"`)
    .join('\n');
  const blocked = blockedPathPatterns
    .map((p) => p.replace(/^\//, '').replace(/[.]/g, '\\.'))
    .join('|');

  return `# Generated by integrations/security-headers.mjs. Do not edit by hand:
# change config/security.mjs and rebuild.

Options -Indexes -MultiViews
ServerSignature Off
FileETag None

<IfModule mod_rewrite.c>
  RewriteEngine On

  # Force HTTPS.
  RewriteCond %{HTTPS} !=on
  RewriteCond %{HTTP:X-Forwarded-Proto} !https
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]

  # Paths automated scanners probe for. Nothing lives there; refuse outright.
  RewriteRule ^(${blocked}) - [F,L,NC]

  # Hidden files (except /.well-known for security.txt and certificate checks).
  RewriteRule (^|/)\\.(?!well-known/) - [F,L]

  # Clean URLs: /about serves about.html.
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME}.html -f
  RewriteRule ^(.+)$ $1.html [L]
</IfModule>

# This base never uses PHP. Refuse to run any PHP file that ends up on the server.
<FilesMatch "\\.(php\\d?|phtml|phar|cgi|pl|py|sh)$">
  Require all denied
</FilesMatch>

<IfModule mod_headers.c>
${headerLines}
  Header always unset X-Powered-By
  Header unset Server
  <If "%{REQUEST_URI} =~ m#^/_astro/#">
    Header set Cache-Control "${immutableAssetHeaders['Cache-Control']}"
  </If>
</IfModule>

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType text/html "access plus 0 seconds"
</IfModule>

ErrorDocument 403 /404.html
ErrorDocument 404 /404.html
`;
}

/** @returns {import('astro').AstroIntegration} */
export default function securityHeaders() {
  return {
    name: 'illuminara:security-headers',
    hooks: {
      'astro:build:done': async ({ dir, logger }) => {
        await writeFile(new URL('_headers', dir), cloudflareHeaders());
        await writeFile(new URL('.htaccess', dir), apacheHtaccess());
        logger.info('Wrote _headers (Cloudflare/Netlify) and .htaccess (Apache/Hostinger)');
      },
    },
  };
}
